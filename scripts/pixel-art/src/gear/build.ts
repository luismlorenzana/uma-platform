// Builds the gear icons: one 32×32 frame per type × grade into packages/art/gear (atlas.png + atlas.json), plus a 3×
// contact sheet and an HTML preview in assets/previews. Ten grades across, one row per type in gear.json's order.
// Run from the repo root: pnpm --filter @uma-platform/pixel-art exec tsx src/gear/build.ts
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { hex } from '../color.ts'
import { ICON_SIZE } from '../icon.ts'
import { encodePng } from '../png.ts'
import { contactSheet } from '../sheet.ts'
import { GEAR } from './index.ts'
import { GRADES } from './spec.ts'
import { checkGearContract, drawGearIcon } from './render.ts'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', '..')
const SIZE = ICON_SIZE
checkGearContract(GEAR)
const W = GRADES * SIZE, H = GEAR.length * SIZE

const atlas = new Uint8Array(W * H * 4)
const frames: Record<string, { x: number; y: number; w: number; h: number; type: string; grade: number; slot: string; material: string }> = {}
const rows: Uint8Array[][] = []
const sections: string[] = []

GEAR.forEach((row, r) => {
  const icons: Uint8Array[] = []
  const figures: string[] = []
  for (const icon of row.icons) {
    const px = drawGearIcon(icon)
    const x = (icon.grade - 1) * SIZE, y = r * SIZE
    for (let k = 0; k < SIZE; k++) atlas.set(px.subarray(k * SIZE * 4, (k + 1) * SIZE * 4), ((y + k) * W + x) * 4)
    frames[icon.id] = { x, y, w: SIZE, h: SIZE, type: row.type.type, grade: icon.grade, slot: row.type.slot, material: icon.material }
    icons.push(px)
    const uri = `data:image/png;base64,${encodePng(SIZE, SIZE, px).toString('base64')}`
    figures.push(
      `<figure class="${icon.grade >= 9 ? 'legendary' : ''}"><img src="${uri}" width="96" height="96" alt=""><img class="x1" src="${uri}" width="32" height="32" alt=""><figcaption>${icon.id}<span>${icon.material}</span></figcaption></figure>`,
    )
  }
  rows.push(icons)
  sections.push(`<section><h2>${row.type.label} <small>${row.type.slot} · ${row.type.mainFamily}</small></h2><div class="grid">${figures.join('')}</div></section>`)
})

const dir = join(ROOT, 'packages', 'art', 'gear')
mkdirSync(dir, { recursive: true })
writeFileSync(join(dir, 'atlas.png'), encodePng(W, H, atlas))
writeFileSync(join(dir, 'atlas.json'), `${JSON.stringify({ schemaVersion: 1, width: W, height: H, frames }, null, 1)}\n`)

const previews = join(ROOT, 'assets', 'previews')
mkdirSync(previews, { recursive: true })
const sheet = contactSheet(rows, 3, 8, hex('#0f141b'), hex('#18202a'))
writeFileSync(join(previews, 'gear.png'), encodePng(sheet.w, sheet.h, sheet.px))
const oneX = contactSheet(rows, 1, 8, hex('#0f141b'), hex('#18202a'))
writeFileSync(join(previews, 'gear-1x.png'), encodePng(oneX.w, oneX.h, oneX.px))
writeFileSync(
  join(previews, 'gear.html'),
  `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Gear icons</title><style>
:root{color-scheme:dark}body{margin:0;padding:16px;background:#0f141b;color:#e6e9ee;font:14px/1.4 system-ui,sans-serif}
h1{font-size:18px;margin:0 0 4px}p{color:#9aa4b2;margin:0 0 16px}h2{font-size:15px;margin:20px 0 8px}h2 small{color:#9aa4b2;font-weight:400}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(120px,1fr));gap:10px}
figure{margin:0;padding:10px;background:#18202a;border-radius:8px;display:grid;justify-items:center;gap:6px}
figure.legendary{box-shadow:inset 0 0 0 1px #c9a24a}img{image-rendering:pixelated}img.x1{opacity:.9}
figcaption{text-align:center;font-weight:600;font-size:12px}figcaption span{display:block;color:#9aa4b2;font-weight:400;font-size:11px}
</style></head><body><h1>Gear icons</h1><p>32×32 originals shown at 3× and 1×, ten grades per type, colored by each grade's refined material. Generated by uma-platform scripts/pixel-art.</p>${sections.join('')}</body></html>`,
)
console.log(`Wrote ${Object.keys(frames).length} gear icons to ${relative(ROOT, dir)} and previews to ${relative(ROOT, previews)}`)
