// Builds every item icon: 32×32 PNGs in assets/items/<family>/, plus a 4× contact sheet and an HTML preview.
// Run from the repo root: pnpm art:draw
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { hex, type RGBA } from './color.ts'
import { FRUITS } from './items/fruits.ts'
import { ORES } from './items/ores.ts'
import type { ItemIcon } from './items/types.ts'
import { encodePng } from './png.ts'
import { Sprite } from './sprite.ts'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..')
const OUT = join(ROOT, 'assets', 'items')
const SIZE = 32

interface Family {
  id: string
  name: string
  side: 'farming' | 'gathering'
  effect: string
  items: ItemIcon[]
}

const FAMILIES: Family[] = [
  { id: 'fruits', name: 'Fruits', side: 'farming', effect: 'MP', items: FRUITS },
  { id: 'ores', name: 'Ores', side: 'gathering', effect: 'ATK', items: ORES },
]

/** Legendary grades (9–10) share one visual rule in every family: glints around the item. */
function draw(item: ItemIcon): Uint8Array {
  const s = new Sprite(SIZE, SIZE)
  s.shadow = { cx: 16, cy: 28, rx: 9.5, ry: 2.2, alpha: 80 }
  item.paint(s)
  if (item.grade >= 9) {
    s.sparkle(5, 7, 2)
    s.sparkle(27, 11, 1)
    s.sparkle(6, 22, 1)
  }
  return s.render()
}

/** Composites scaled icons onto a background, nearest-neighbor. */
function sheet(rows: Uint8Array[][], scale: number, pad: number, bg: RGBA, cell: RGBA): { w: number; h: number; px: Uint8Array } {
  const cols = Math.max(...rows.map((r) => r.length))
  const cellSize = SIZE * scale
  const w = cols * cellSize + (cols + 1) * pad
  const h = rows.length * cellSize + (rows.length + 1) * pad
  const px = new Uint8Array(w * h * 4)
  for (let i = 0; i < w * h; i++) px.set(bg, i * 4)
  rows.forEach((row, ry) =>
    row.forEach((icon, rx) => {
      const ox = pad + rx * (cellSize + pad), oy = pad + ry * (cellSize + pad)
      for (let y = 0; y < cellSize; y++)
        for (let x = 0; x < cellSize; x++) {
          const o = ((oy + y) * w + ox + x) * 4
          px.set(cell, o)
          const i = (Math.floor(y / scale) * SIZE + Math.floor(x / scale)) * 4
          const a = (icon[i + 3] ?? 0) / 255
          for (let k = 0; k < 3; k++) px[o + k] = Math.round((icon[i + k] ?? 0) * a + (px[o + k] ?? 0) * (1 - a))
        }
    }),
  )
  return { w, h, px }
}

const rows: Uint8Array[][] = []
const cards: string[] = []
for (const family of FAMILIES) {
  const dir = join(OUT, family.id)
  mkdirSync(dir, { recursive: true })
  const row: Uint8Array[] = []
  const items = family.items.map((item) => {
    const px = draw(item)
    const png = encodePng(SIZE, SIZE, px)
    writeFileSync(join(dir, `${item.id}.png`), png)
    row.push(px)
    return { item, uri: `data:image/png;base64,${png.toString('base64')}` }
  })
  rows.push(row)
  cards.push(`<section><h2>${family.name} <small>${family.side} · ${family.effect}</small></h2><div class="grid">${items
    .map(({ item, uri }) => `<figure class="${item.grade >= 9 ? 'legendary' : ''}"><img src="${uri}" width="128" height="128" alt=""><img class="x1" src="${uri}" width="32" height="32" alt=""><figcaption>${item.name}<span>Grade ${item.grade}</span></figcaption></figure>`)
    .join('')}</div></section>`)
}

const previews = join(ROOT, 'assets', 'previews')
mkdirSync(previews, { recursive: true })
const contact = sheet(rows, 4, 12, hex('#0f141b'), hex('#18202a'))
writeFileSync(join(previews, 'items.png'), encodePng(contact.w, contact.h, contact.px))
writeFileSync(
  join(previews, 'items.html'),
  `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Item icons</title><style>
:root{color-scheme:dark}body{margin:0;padding:16px;background:#0f141b;color:#e6e9ee;font:14px/1.4 system-ui,sans-serif}
h1{font-size:18px;margin:0 0 4px}p{color:#9aa4b2;margin:0 0 16px}h2{font-size:15px;margin:20px 0 8px}h2 small{color:#9aa4b2;font-weight:400}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(150px,1fr));gap:10px}
figure{margin:0;padding:10px;background:#18202a;border-radius:8px;display:grid;justify-items:center;gap:6px}
figure.legendary{box-shadow:inset 0 0 0 1px #c9a24a}img{image-rendering:pixelated}img.x1{opacity:.9}
figcaption{text-align:center;font-weight:600}figcaption span{display:block;color:#9aa4b2;font-weight:400;font-size:12px}
</style></head><body><h1>Item icons</h1><p>32×32 originals shown at 4× and 1×. Generated by uma-platform scripts/pixel-art.</p>${cards.join('')}</body></html>`,
)
console.log(`Wrote ${FAMILIES.reduce((n, f) => n + f.items.length, 0)} icons to ${relative(ROOT, OUT)} and previews to ${relative(ROOT, previews)}`)
